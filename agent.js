// Plain words: a member may read this. No dash used as a pause, and the word is yacht.
function when(ms) {
  if (!ms || !Number.isFinite(Number(ms))) return "unknown";
  return new Date(Number(ms)).toISOString().replace("T", " ").slice(0, 16) + " UTC";
}

function say(proposals, facts) {
  const L = [];
  L.push("Ready to sign, for " + facts.wallet);
  L.push("prepared " + facts.at + ". Nothing here has been signed or sent.");
  L.push("");
  if (!proposals.length) {
    L.push("  Nothing is open to this wallet that it has not already done.");
    return L;
  }
  proposals.forEach((p, i) => {
    L.push("  " + (i + 1) + ". " + p.act.toUpperCase() + "  " + p.what);
    L.push("     send to:   " + p.endpoint);
    L.push("     sign this, exactly, with " + facts.wallet + ":");
    p.sign.split("\n").forEach((line) => L.push("       | " + line));
    L.push("     then post: " + JSON.stringify(Object.assign({}, p.body, { signature: "0x<the signature>" })));
    L.push("     good until " + when(p.goesStaleAt) + ", because it depends on " + p.dependsOn + ".");
    L.push("");
  });
  L.push("  " + proposals.length + " act" + (proposals.length === 1 ? "" : "s") + " prepared.");
  L.push("  A proposal is only worth signing while what it depends on has not moved. Read again");
  L.push("  rather than keeping one: an old signature is refused, and the refusal will not say why.");
  return L;
}


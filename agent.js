// Plain words, and no dash used as a pause: a member reads this. [[plain-words-rule]]
function say(result, orders) {
  const L = [];
  L.push("Standing orders for " + orders.wallet + (orders.actingYacht ? ", acting through yacht #" + orders.actingYacht : ", with no agent key named") + ".");
  // The ceiling is said out loud every time, because a cap a member has forgotten they wrote is a
  // cap that will surprise them, and the club refuses to write one for them.
  if (orders.budget) {
    const said = Object.keys(orders.budget).map((u) =>
      Object.keys(orders.budget[u]).map((per) => amount(u, orders.budget[u][per]) + " " + PERIODS[per]).join(", "));
    L.push("Your budget: " + said.join(", and ") + ". You wrote it, and it binds your agent, not you.");
  } else {
    L.push("You wrote no budget, so your agent will not spend anything at all.");
  }
  L.push("");
  if (result.execute.length) {
    L.push("YOUR AGENT CAN DO THESE NOW:");
    result.execute.forEach((p) => L.push("  " + p.what + (p.spends ? "  (" + p.spends.amount + " " + (p.spends.unit === "eth" ? "ETH" : "Anchor Points") + ")" : "")));
  } else {
    L.push("There is nothing your agent can do by itself right now.");
  }
  if (result.propose.length) {
    L.push("");
    L.push("THESE NEED YOUR OWN HAND:");
    result.propose.forEach((p) => L.push("  " + p.what + "\n    " + p.why));
  }
  if (result.quiet.length) {
    L.push("");
    result.quiet.forEach((q) => L.push("  " + q.act + ": " + q.why));
  }
  // ☠ SAID EVERY TIME, not once in a help page: a member reading this list has to know that the cap
  // above does not cover what calldata can do. It is the one thing about this act that surprises
  // people, and the surprise costs everything in the account.
  if (result.execute.concat(result.propose).some((x) => x.chain)) {
    L.push("");
    L.push("A CHAIN CALL IS NOT LIKE THE OTHERS. It is a transaction your yacht's own account makes on");
    L.push("Ethereum, and it can do anything that account can do. Your ETH budget limits what a call");
    L.push("SENDS. It does not limit what the calldata does: one approval can hand away everything in");
    L.push("there. Keep in that account only what you would let it spend.");
  }
  L.push("");
  L.push("This file chose nothing. It matched what you wrote against what the club publishes.");
  return L.join("\n");
}


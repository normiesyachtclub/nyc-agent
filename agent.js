// Does this wallet hold that yacht? `true` also when the club could not tell us, because "we could
// not read it" and "no" are different answers and only one of them is a reason to refuse.
function ownsOrUnknown(seen, yachtId) {
  const c = seen && seen.chandlery && seen.chandlery.state === "open" ? seen.chandlery.data : null;
  if (!c || !Array.isArray(c.ids)) return true;
  return c.ids.map(String).indexOf(String(yachtId)) >= 0;
}

// ---- proposing ---------------------------------------------------------------------------------
// Pure: facts in, proposals out. No network of its own, so a caller that already has the facts (an
// agent runtime with its own clock) never pays for a second read of the club.
// ⚑ `opts.actingYacht` (3 Sep 2026): when a DELEGATED key will sign, the two captain-scope acts need
// the yacht whose account authorises it, sent beside the signature and NOT part of the signed bytes.
// It is added here rather than by the caller so that "the exact request to send" stays one thing in
// one file. ☠ It is only ever a value the MEMBER supplied: this file never picks a yacht, the same
// rule that keeps it from picking one to commit.
function propose(facts, opts) {
  const o = opts || {};
  const now = o.now || Date.now();
  const wallet = facts.wallet;
  const out = [];
  if (!wallet) return out;
  const acting = /^\d{1,7}$/.test(String(o.actingYacht || "")) ? String(o.actingYacht) : null;
  // Only the acts a delegated key may actually sign carry it. Sending it anywhere else would be
  // noise the relay ignores, and noise in a published request shape is how integrators learn wrong
  // things. The list is deliberately short and matches what /api/v1/signing.json declares.
  const DELEGATABLE = { "daily-tide": true, "muster": true };
  const withActing = (act, body) => (acting && DELEGATABLE[act] ? Object.assign({}, body, { actingYacht: acting }) : body);
  const s = facts.seen || {};
  const D = (r) => (r && r.state === "open" && r.data) || null;

  // 1. today's free draw. Costs nothing, so it is the first thing worth proposing.
  const daily = D(s.daily);
  if (daily && daily.tide && daily.tide.entered === false) {
    const day = daily.tide.day;
    const m = { day, wallet, nonce: nonce() };
    out.push({
      act: "daily-tide",
      what: "Enter today's free draw. It costs no Anchor Points.",
      endpoint: "POST " + RELAY + "/tide/daily/enter",
      sign: MESSAGES.dailyTide(m),
      body: withActing("daily-tide", Object.assign({}, m)),
      dependsOn: "the day, which the relay reads from its own clock",
      goesStaleAt: daily.tide.closesAt || nextUtcMidnight(now)
    });
  }

  // 2. today's watch. The Cup is ranked on watches kept, and a day missed cannot be made up.
  const st = D(s.standing);
  if (st && st.entry && st.entry.musteredToday === false) {
    const season = (st.season && st.season.id) || (D(s.regatta) && D(s.regatta).season.id);
    if (season) {
      const day = new Date(now).toISOString().slice(0, 10);
      const m = { season, day, wallet, nonce: nonce() };
      out.push({
        act: "muster",
        what: "Keep today's watch. A day missed cannot be made up later.",
        endpoint: "POST " + RELAY + "/regatta/checkin",
        sign: MESSAGES.muster(m),
        body: withActing("muster", Object.assign({}, m)),
        dependsOn: "the season and the day, both the relay's",
        goesStaleAt: nextUtcMidnight(now)
      });
    }
  }

  // 3. a commit to the open Tide round. Only when a yacht was named: the club must never choose one
  // on a member's behalf, and there is no honest way to pick which yacht somebody commits.
  //
  // ⚠ AND ONLY IF THE WALLET REALLY HOLDS IT. `/chandlery/<wallet>` already carries `ids`, so this
  // costs no extra read. Preparing an act the relay is certain to refuse is worse than preparing
  // nothing: the member signs, is turned away, and has no way to tell a wrong yacht from a stale
  // round. ☠ But an UNREADABLE chandlery is not a "no" — same rule as rung 0, where a timeout is
  // never a shut door. Unknown means propose and let the club be the judge.
  const tide = D(s.tide);
  if (tide && tide.round && !tide.round.closed && o.yachtId && ownsOrUnknown(s, o.yachtId)) {
    const r = tide.round;
    const m = { round: r.id, yachtId: String(o.yachtId), wallet, nonce: nonce() };
    out.push({
      act: "tide-commit",
      what: "Commit yacht #" + o.yachtId + " to Tide round " + r.id + ". It costs " + r.cost +
            " Anchor Points, and a wallet may commit " + r.cap + " times.",
      endpoint: "POST " + RELAY + "/tide/commit",
      sign: MESSAGES.tideCommit(m),
      body: Object.assign({}, m),
      dependsOn: "round " + r.id + ", which dies the moment the round is called",
      goesStaleAt: r.closesAt || null
    });
  }

  // 4. a call the yacht's own account makes on Ethereum.
  //
  // ☠☠ THIS ONE DOES NOT GO TO THE CLUB AT ALL, and that is the whole point of it. Everything above
  // is a message to sign and a route to post it to; this is a transaction, and the club is not in the
  // path. It is built HERE anyway, and not in the planner, for the same reason as the other three:
  // "the exact thing to send" lives in one file or it drifts.
  //
  // ☠ EVERY FIELD COMES FROM THE MEMBER. There is no target in this file, no default contract, and no
  // way for the club to put one here. `o.chainCall` is what they wrote, checked by the language before
  // it ever reaches this line.
  //
  // ⚠ AND IT NEEDS THE ACCOUNT, WHICH IS THE ACTING YACHT'S. Without one there is nothing to act
  // through, so nothing is prepared: the club will not pick a yacht to spend from.
  if (o.chainCall && acting) {
    const c = o.chainCall;
    const value = String(c.value || "0");
    out.push({
      act: "chain-call",
      what: "Have yacht #" + acting + "'s account call " + c.to +
            (value !== "0" ? " and send " + value + " ETH" : "") + ".",
      chain: { actingYacht: acting, to: c.to, value: value, data: String(c.data || "0x"), operation: 0 },
      // ⚠ It cannot go stale the way a signed message can: there is no round, no day and no nonce in
      // it. What CAN change is the chain, which is why the runner simulates before it sends.
      dependsOn: "nothing the club controls. It is a transaction on Ethereum",
      goesStaleAt: null
    });
  }

  // ---- 5-7. 🏝 WORK ON THE ISLANDS (17 Sep 2026) -------------------------------------------------
  // ☠☠ EVERY CHOICE BELOW IS THE MEMBER'S OR A NEUTRAL ORDER, NEVER A JUDGEMENT. Which discipline,
  // which yacht, which venue and which currency are what the member wrote. When more than one open
  // part fits, the OLDEST posted comes first and its parts in the order the principal declared them:
  // that is an order anybody can re-derive, and it says nothing about which work is better. There is
  // no word here for pay, and nothing reads the terms a principal wrote.
  const w = o.work || null;
  const opps = D(s.opportunities);
  const board = opps && Array.isArray(opps.opportunities) ? opps.opportunities : null;
  const lower = (x) => String(x == null ? "" : x).toLowerCase();
  // The parts this wallet took and has not handed in, oldest first. One list, used three times.
  const owed = [];
  (board || []).forEach((opp) => {
    if (opp.status === "settled" || opp.status === "expired") return;
    if (!(Number(opp.deadline) > now)) return;
    (opp.joined || []).forEach((j) => {
      if (lower(j.captain) !== lower(wallet)) return;
      if ((opp.delivered || []).some((d) => d.part === j.part)) return;
      owed.push({ opp, part: j.part, yachtId: String(j.yachtId), at: Number(j.at) || 0 });
    });
  });
  owed.sort((a, b) => a.at - b.at);
  // What the RUNNER recorded this member's agent doing on-chain. ☠ Only calls it really sent, from the
  // named yacht's account, that the chain reported as worked and that no act has used yet: the agent
  // never names somebody else's transaction, and never the same one twice.
  const calls = Array.isArray(o.calls) ? o.calls : null;
  const freeCalls = (yacht, after) => (calls || [])
    .filter((c) => c && String(c.yacht) === String(yacht) && Number(c.status) === 1 && !c.used &&
                   // ⚠ Five minutes of grace: the member's clock and the relay's are two clocks, and a call
                   // sent right after taking a part must not be ruled "before" it by a slow wristwatch.
                   /^0x[0-9a-fA-F]{64}$/.test(String(c.hash)) && Number(c.at) >= (after ? after - 300000 : 0))
    .sort((a, b) => Number(a.at) - Number(b.at));

  // 5. TAKE A PART. ☠ One part at a time per yacht: an agent that took every open part in the club
  // would be a crew of one by the back door, and a part it cannot hand in is somebody else's lost job.
  if (w && w.join && board) {
    const j = w.join, yacht = String(j.yacht);
    const comp = D(s["competence:" + yacht]);
    const level = comp && comp.competences && comp.competences[j.discipline]
      ? Number(comp.competences[j.discipline].level) : null;
    const busy = owed.some((x) => x.yachtId === yacht);
    // ☠ An unread level is not level 0: without it the agent does not guess which work it can take.
    if (!busy && level !== null && Number.isFinite(level) && ownsOrUnknown(s, yacht)) {
      const fits = board.filter((opp) =>
        opp.status === "open" && Number(opp.deadline) > now && opp.discipline === j.discipline &&
        (j.venue == null || String(opp.venue) === String(j.venue)) &&
        (j.paidIn == null || lower(opp.currency) === lower(j.paidIn)) &&
        !(opp.principal && lower(opp.principal.wallet) === lower(wallet)) &&
        !(opp.joined || []).some((x) => lower(x.captain) === lower(wallet)) &&
        (opp.requiresHere != null ? Number(opp.requiresHere) : Number(opp.requires) || 0) <= level
      ).sort((a, b) => (Number(a.postedAt) || 0) - (Number(b.postedAt) || 0));
      for (const opp of fits) {
        const free = (opp.parts || []).find((p) => !(opp.joined || []).some((x) => x.part === p.key));
        if (!free) continue;
        const m = { oppId: opp.id, part: free.key, yachtId: yacht, wallet, nonce: nonce() };
        out.push({
          act: "work-join",
          what: "Take the part \"" + free.key + "\" of " + opp.id + " with yacht #" + yacht + ", paid in " +
                (opp.currencyLabel || opp.currency || "the currency it was posted in") + ".",
          endpoint: "POST " + RELAY + "/opportunities/join",
          sign: MESSAGES.workJoin(m),
          body: { oppId: m.oppId, part: m.part, yachtId: Number(yacht), wallet: m.wallet, nonce: m.nonce },
          dependsOn: "the part still being free, which another captain can change at any moment",
          goesStaleAt: Number(opp.deadline) || null
        });
        break;
      }
    }
  }

  // 6. HAND IN A PART, with a transaction this agent sent from that yacht's account AFTER taking it.
  if (w && w.deliver && board) {
    const yacht = String(w.deliver.yacht);
    const todo = owed.find((x) => x.yachtId === yacht);
    const call = todo ? freeCalls(yacht, todo.at)[0] : null;
    if (todo && call) {
      const m = { oppId: todo.opp.id, part: todo.part, yachtId: yacht, txHash: String(call.hash), wallet, nonce: nonce() };
      out.push({
        act: "work-deliver",
        what: "Hand in \"" + todo.part + "\" of " + todo.opp.id + " with the transaction " + String(call.hash).slice(0, 12) + "… your agent sent from yacht #" + yacht + ".",
        endpoint: "POST " + RELAY + "/opportunities/deliver",
        sign: MESSAGES.workDeliver(m),
        body: { oppId: m.oppId, part: m.part, note: w.deliver.note ? String(w.deliver.note).slice(0, 120) : "",
                txHash: lower(m.txHash), wallet: m.wallet, nonce: m.nonce },
        usesCall: String(call.hash),
        dependsOn: "the part not being handed in or closed already",
        goesStaleAt: Number(todo.opp.deadline) || null
      });
    }
  }

  // 7. RECORD WHAT THE YACHT DID. ☠ It waits while that yacht still owes a part: the transaction may be
  // the one the delivery needs, and a claim would put it on the record first and make the delivery fail.
  // ☠ And an unread board is not an empty one: without it the agent cannot know whether the yacht owes
  // a part, so it records nothing rather than risk taking the delivery's transaction.
  if (w && w.claim && board) {
    const yacht = String(w.claim.yacht);
    // ☠ A part being TAKEN in this same plan counts as owed (found by the agent smoke, 17 Sep): the club
    // has not recorded the join yet, so `owed` cannot see it, and the claim would spend the one
    // transaction the delivery is about to need.
    const waiting = owed.some((x) => x.yachtId === yacht) ||
      out.some((x) => x.act === "work-join" && String(x.body && x.body.yachtId) === yacht);
    const call = waiting ? null : freeCalls(yacht, 0)[0];
    if (call) {
      const m = { yachtId: yacht, discipline: w.claim.discipline, txHash: String(call.hash), wallet, nonce: nonce() };
      out.push({
        act: "competence-claim",
        what: "Record the transaction " + String(call.hash).slice(0, 12) + "… from yacht #" + yacht + " as " + w.claim.discipline + ".",
        endpoint: "POST " + RELAY + "/competences/claim",
        sign: MESSAGES.competenceClaim(m),
        body: { yachtId: Number(yacht), discipline: m.discipline, txHash: lower(m.txHash), wallet: m.wallet, nonce: m.nonce },
        usesCall: String(call.hash),
        dependsOn: "nothing but the chain: the club reads the transaction when it arrives",
        goesStaleAt: null
      });
    }
  }

  // 6. 🎉 a line in the Crew Mess (23 Sep 2026). The WORDS are never this file's: they come in as
  // `opts.mess`, written by the member's own voice or by the runner's plain status line, and this only
  // wraps them in the message the relay checks. The speaker is the acting yacht and nobody else,
  // because a line is accepted only from a key that yacht's own account authorised.
  const mess = D(s.mess);
  if (mess && o.mess && acting && typeof o.mess.text === "string" && o.mess.text) {
    const m = { yacht: acting, wallet, day: new Date(now).toISOString().slice(0, 10),
      replyTo: o.mess.replyTo != null && /^\d{1,9}$/.test(String(o.mess.replyTo)) ? String(o.mess.replyTo) : null,
      nonce: nonce(), text: o.mess.text };
    out.push({
      act: "mess-say",
      what: "Say in the Crew Mess, as yacht #" + acting + (m.replyTo ? ", answering #" + m.replyTo : "") + ": " + m.text,
      endpoint: "POST " + RELAY + "/mess/say",
      sign: MESSAGES.messSay(m),
      body: m,
      dependsOn: "the day, which the relay reads from its own clock",
      goesStaleAt: nextUtcMidnight(now)
    });
  }

  return out;
}


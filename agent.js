// ---- reading ---------------------------------------------------------------------------------
// One shape for every answer, so a caller never has to tell "shut" from "unreachable" by guessing.
// `state` is one of: "open" (200 and parsed), "shut" (404, dark by design), "unreadable" (anything
// else, including a timeout). The last one is never treated as a finding.
// ⚑ PLAIN http ONLY FOR THIS MACHINE (17 Sep 2026, found by the agent smoke). `NYC_RELAY` can name a
// relay a builder runs locally, and that one speaks http. ☠ Anywhere else it stays https: the answers
// read here decide what the agent SIGNS, and a board rewritten in transit would have it take work
// somebody else chose, with a signature the real relay accepts.
const LOCAL = /^http:\/\/(127\.0\.0\.1|localhost)(:\d+)?\//;
function get(url, timeoutMs) {
  return new Promise((resolve) => {
    if (/^http:/.test(url) && !LOCAL.test(url)) {
      return resolve({ state: "unreadable", status: 0, why: "plain http is only read from this machine" });
    }
    const lib = LOCAL.test(url) ? require("http") : https;
    const req = lib.get(url, { headers: { accept: "application/json" } }, (res) => {
      let body = "";
      res.on("data", (c) => (body += c));
      res.on("end", () => {
        if (res.statusCode === 404) return resolve({ state: "shut", status: 404 });
        if (res.statusCode !== 200) return resolve({ state: "unreadable", status: res.statusCode });
        // ⚠ NOT EVERY OPEN DOOR SPEAKS JSON. `/health` and `/` are plain text by design, and the
        // first run of this file reported the whole club unreachable because `JSON.parse` threw on
        // "ok sailors=1 index=825". A 200 is an open door whatever it is written in.
        try { resolve({ state: "open", status: 200, data: JSON.parse(body) }); }
        catch (e) { resolve({ state: "open", status: 200, text: body.slice(0, 400) }); }
      });
    });
    req.on("error", (e) => resolve({ state: "unreadable", status: 0, why: e.message }));
    req.setTimeout(timeoutMs || 20000, () => { req.destroy(); resolve({ state: "unreadable", status: 0, why: "timed out" }); });
  });
}


/*
 * askBrain — run the member's own judgement, and let it HOLD BACK acts the rules already allowed.
 * ================================================================================================
 * ☠☠ A BRAIN IS A VETO, NEVER A PERMIT, AND THAT IS THE WHOLE SAFETY ARGUMENT. It is asked only
 * about acts in `mayPropose`, which the member has already written orders for; for those acts its
 * approval is required IN ADDITION to every condition and the budget. So plugging a model in can
 * only ever make an agent do LESS than the rules allow, never more. Exactly like the budget: it
 * binds the agent, not the member.
 *
 * ☠ IT FAILS CLOSED, in every direction. No answer, bad JSON, a non-zero exit, a timeout, a name it
 * was not asked about: the act simply does not fire, and the reason is printed. Same rule as a fact
 * the club could not be read for. A brain that has broken must never look like a brain that said yes.
 *
 * ⚑ THE CLUB RUNS NOTHING AND KNOWS NOTHING ABOUT THE MODEL. This spawns a command the member wrote
 * in their own file, on their own machine, and reads its stdout. Whatever credential it needs is its
 * own business: nothing here names a provider, and nothing here ever sees a key.
 */
function askBrain(brain, facts, acts) {
  return new Promise((resolve) => {
    if (!brain) return resolve({ used: false, approved: null, why: {}, note: null });
    const { spawn } = require("child_process");
    // ⚑ 19 Sep 2026: `readings` are the same named figures a `when` condition uses (anchorPoints,
    // roundCommitted…), read by the language's own readers. Until this day a brain got only the raw
    // payloads, while the template's examples read `facts.anchorPoints`, which was always undefined:
    // an example that silently did nothing. `null` means the club could not be read for it, never zero.
    // `about` says what each act it may decide about does, in the language's own words.
    const readings = {};
    Object.keys(SO.FIELDS).forEach((k) => {
      let v; try { v = SO.FIELDS[k].read((facts && facts.seen) || {}); } catch (e) { v = undefined; }
      readings[k] = v === undefined ? null : v;
    });
    const about = {};
    brain.mayPropose.forEach((a) => { about[a] = (SO.ACTS[a] && SO.ACTS[a].what) || a; });
    const ask = { mayPropose: brain.mayPropose, about: about, readings: readings, facts: facts, askedAt: new Date().toISOString() };
    let child;
    // ⚠ `shell: true` because this is the member's own command line, written by them, in a file only
    // they can edit — the same trust already given to `agent-key.txt` sitting beside it. It is their
    // machine and their key; the club is not a sandbox and must not pretend to be one.
    try { child = spawn(brain.command, { shell: true, stdio: ["pipe", "pipe", "pipe"] }); }
    catch (e) { return resolve({ used: true, approved: [], why: {}, note: "your brain would not start (" + e.message + "), so nothing it decides about will run" }); }
    let out = "", err = "", done = false;
    const finish = (r) => { if (done) return; done = true; try { child.kill(); } catch (e) {} resolve(r); };
    const timer = setTimeout(() => finish({ used: true, approved: [], why: {},
      note: "your brain did not answer within " + brain.timeoutSeconds + "s, so nothing it decides about will run" }),
      brain.timeoutSeconds * 1000);
    child.stdout.on("data", (d) => { out += d; });
    child.stderr.on("data", (d) => { err += d; });
    child.on("error", (e) => { clearTimeout(timer); finish({ used: true, approved: [], why: {}, note: "your brain would not start (" + e.message + ")" }); });
    child.on("close", (code) => {
      clearTimeout(timer);
      if (code !== 0) return finish({ used: true, approved: [], why: {},
        note: "your brain exited with code " + code + (err.trim() ? " (" + err.trim().split("\n")[0].slice(0, 120) + ")" : "") });
      let ans;
      try { ans = JSON.parse(out); } catch (e) {
        return finish({ used: true, approved: [], why: {}, note: "your brain did not print JSON, so nothing it decides about will run" });
      }
      const list = Array.isArray(ans && ans.propose) ? ans.propose.map(String) : null;
      if (!list) return finish({ used: true, approved: [], why: {},
        note: "your brain printed no \"propose\" list, so nothing it decides about will run" });
      // ☠ NARROWED TO WHAT IT WAS ASKED ABOUT. A brain naming an act outside `mayPropose` is not an
      // error to argue with, it is simply not listened to — the member's file is the boundary.
      const stray = list.filter((a) => brain.mayPropose.indexOf(a) < 0);
      const approved = list.filter((a) => brain.mayPropose.indexOf(a) >= 0);
      finish({ used: true, approved: approved, why: (ans && ans.why) || {},
        note: stray.length ? "your brain also named " + stray.join(", ") + ", which it was not asked about and was ignored" : null });
    });
    try { child.stdin.write(JSON.stringify(ask)); child.stdin.end(); } catch (e) {}
  });
}


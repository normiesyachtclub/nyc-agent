const isAddr = (a) => /^0x[0-9a-fA-F]{40}$/.test(String(a || ""));
const isYacht = (y) => /^\d{1,7}$/.test(String(y == null ? "" : y));
const isCount = (n) => typeof n === "number" && Number.isFinite(n) && n >= 0 && Math.floor(n) === n;

/*
 * parse(textOrObject) -> { ok, orders, problems }
 * ⚠ IT REFUSES RATHER THAN REPAIRS. A standing order that runs while a member believes it says
 * something else is worse than one that does not run at all, so every problem is named and nothing
 * is guessed at. `problems` is written to be read by a person.
 */
function parse(input) {
  const problems = [];
  let doc = input;
  if (typeof input === "string") {
    try { doc = JSON.parse(input); }
    catch (e) { return { ok: false, orders: null, problems: ["that file is not valid JSON: " + e.message] }; }
  }
  if (!doc || typeof doc !== "object") return { ok: false, orders: null, problems: ["there are no orders in there"] };

  if (Number(doc.version) !== 1) problems.push("this file needs \"version\": 1");
  if (!isAddr(doc.wallet)) problems.push("\"wallet\" must be the captain's address");
  // ⚠ `actingYacht` is only needed when a delegated key will sign. A member running this themselves
  // does not need one, so it is checked when present and never demanded.
  if (doc.actingYacht != null && !isYacht(doc.actingYacht)) problems.push("\"actingYacht\" must be a yacht id");
  // 👁 KEEP ME POSTED (19 Sep 2026, the first ready job): an agent that only tells its member what is
  // open to them, with no key and no act. ☠ A boolean and nothing else: "yes" or 1 would be a member
  // believing they are being told when the runner reads it as off. With it on, the list of acts may be
  // empty, because watching and telling is a whole job on its own.
  if (doc.keepMePosted !== undefined && typeof doc.keepMePosted !== "boolean") {
    problems.push("\"keepMePosted\" must be true or false, written without quotes");
  }
  const posting = doc.keepMePosted === true;
  if (!Array.isArray(doc.orders) || (!doc.orders.length && !posting)) {
    problems.push("\"orders\" must be a list with at least one order in it, unless \"keepMePosted\" is true");
  }

  // ☠ THE CAP THE CONTRACT DOES NOT HAVE. It is optional because most orders cost nothing, and it is
  // never invented: no budget means no budget, and an act that costs simply will not be executed.
  const budget = parseBudget(doc.budget, problems);

  const orders = [];
  const already = {};
  (Array.isArray(doc.orders) ? doc.orders : []).forEach((o, i) => {
    const where = "order " + (i + 1);
    if (!o || typeof o !== "object") { problems.push(where + " is not an order"); return; }
    const act = String(o.act || "");
    if (!ACTS[act]) {
      problems.push(where + ": there is no act called \"" + act + "\". The acts are: " + Object.keys(ACTS).join(", "));
      return;
    }
    // ⚠ Two orders for one act would mean one of them silently losing, which is the same defect as
    // a field quietly dropped: a member believing a rule is in force when it is not.
    if (already[act]) { problems.push(where + ": there are already orders for \"" + act + "\", and only one set can be in force"); return; }
    already[act] = true;
    // ☠ THE FREE VARIABLE. This is the line the whole file exists for: an act that needs a binding
    // and does not have one is refused, never filled in.
    const missing = ACTS[act].needs.filter((k) => !(NEEDS[k] || (() => false))(o[k]));
    if (missing.length) {
      problems.push(where + " (" + act + ") needs " + missing.join(", ") +
        ", and the club will not choose one for you");
      return;
    }
    // Anything we do not understand is refused too, because a field silently ignored is a member
    // believing something is in force when it is not.
    const known = ACTS[act].needs.concat(ACTS[act].optional || []);
    const extra = Object.keys(o).filter((k) => k !== "act" && k !== "when" && known.indexOf(k) < 0);
    if (extra.length) { problems.push(where + ": nothing here understands " + extra.join(", ")); return; }
    // ☠ A chain call is the one order that leaves the club, so its two optional fields are checked
    // hard. An amount is a STRING because a JSON number cannot hold wei, and calldata is hex or it is
    // nothing: a half-typed `data` is a transaction that does something other than what was meant.
    // ☠ A STRING, AND CONVERTIBILITY IS NOT THE TEST. `String(0.01)` is "0.01", so a JSON number
    // sailed through the first version of this check. It is the TYPE that matters: 0.1 + 0.2 is
    // 0.30000000000000004, and an amount that changed on the way in is an amount nobody can audit.
    if (o.value !== undefined && (typeof o.value !== "string" || toWei(o.value) === null)) {
      problems.push(where + ": \"value\" must be an amount of ETH written in quotes, like \"0.01\"");
      return;
    }
    if (o.data !== undefined && !/^0x([0-9a-fA-F]{2})*$/.test(String(o.data))) {
      problems.push(where + ": \"data\" must be hex starting 0x, with an even number of digits");
      return;
    }
    const badOptional = Object.keys(OPTIONAL_CHECK).find((k) => o[k] !== undefined && known.indexOf(k) >= 0 && !OPTIONAL_CHECK[k].ok(o[k]));
    if (badOptional) { problems.push(where + ": " + OPTIONAL_CHECK[badOptional].say); return; }
    if (o.when !== undefined && !parseWhen(o.when, where + " (" + act + ")", problems)) return;
    orders.push(Object.assign({ act }, o));
  });

  // ☠☠ THE TOP LEVEL WAS THE ONE PLACE A TYPO STILL PASSED IN SILENCE (closed 4 Sep 2026).
  // Every order refuses a field it does not understand, and every budget does, because "a field
  // silently ignored is a member believing something is in force when it is not". The document
  // itself did not. `brain` made that gap expensive: a member writing "brains" or "Brain" would have
  // got an agent with no judgement and no way to tell, so the same rule now applies here.
  const TOP = ["version", "wallet", "actingYacht", "budget", "brain", "keepMePosted", "orders"];
  const strayTop = Object.keys(doc).filter((k) => TOP.indexOf(k) < 0);
  if (strayTop.length) problems.push("nothing here understands " + strayTop.join(", ") +
    ". This file understands " + TOP.join(", "));

  // ⚑ AFTER the orders are parsed, because a brain may only propose acts the member actually wrote.
  const brain = parseBrain(doc.brain, orders.map((o) => o.act), problems);

  if (problems.length) return { ok: false, orders: null, problems };
  return { ok: true, orders: {
    wallet: String(doc.wallet).toLowerCase(),
    actingYacht: doc.actingYacht == null ? null : String(doc.actingYacht),
    budget: budget,
    brain: brain,
    keepMePosted: posting,
    list: orders
  }, problems: [] };
}

/*
 * parseWhen — the conditions, refused the same way as everything else.
 * ☠ An unknown FIELD is refused and the real ones are named. The alternative is a member writing
 * `whenCheap` and watching their agent run anyway, which is the worst outcome available here: a rule
 * that looks in force and is not.
 */
function parseWhen(when, where, problems) {
  if (!when || typeof when !== "object" || Array.isArray(when)) {
    problems.push(where + ": \"when\" must name at least one fact and a threshold");
    return false;
  }
  const names = Object.keys(when);
  if (!names.length) { problems.push(where + ": \"when\" names nothing, so it holds nothing back"); return false; }
  let good = true;
  names.forEach((f) => {
    const field = FIELDS[f];
    if (!field) {
      problems.push(where + ": there is no fact called \"" + f + "\". The facts you may write a condition over are: " + Object.keys(FIELDS).join(", "));
      good = false; return;
    }
    const c = when[f];
    if (!c || typeof c !== "object" || Array.isArray(c)) {
      problems.push(where + ": \"" + f + "\" needs one of " + Object.keys(TESTS).join(", "));
      good = false; return;
    }
    const ops = Object.keys(c);
    if (!ops.length) { problems.push(where + ": \"" + f + "\" says nothing"); good = false; return; }
    ops.forEach((op) => {
      const t = TESTS[op];
      if (!t) {
        problems.push(where + ": there is no test called \"" + op + "\". The tests are: " + Object.keys(TESTS).join(", "));
        good = false; return;
      }
      if (t.kinds.indexOf(field.kind) < 0) {
        problems.push(where + ": \"" + op + "\" does not apply to " + f + ", which is " + (field.kind === "number" ? "a number" : "a name"));
        good = false; return;
      }
      const v = c[op];
      if (field.kind === "number" && !(typeof v === "number" && Number.isFinite(v))) {
        problems.push(where + ": " + f + " " + op + " needs a number");
        good = false; return;
      }
      if (field.kind === "name" && !(typeof v === "string" && v.length)) {
        problems.push(where + ": " + f + " " + op + " needs a name in quotes");
        good = false;
      }
    });
  });
  return good;
}

/*
 * parseBudget — the ceiling, in Anchor Points, written by the member.
 * ☠ There is no default and there never will be. A club-written cap is the club deciding how much
 * of a member's standing may be spent for them, which is the same act as choosing what to spend it
 * on, in different clothes.
 */
function parseBudget(budget, problems) {
  if (budget === undefined || budget === null) return null;
  if (typeof budget !== "object" || Array.isArray(budget)) { problems.push("\"budget\" must say what may be spent, like { \"anchorPoints\": { \"perDay\": 300 } }"); return null; }
  const units = Object.keys(budget);
  const unknown = units.filter((k) => !UNITS[k]);
  if (unknown.length) { problems.push("\"budget\" does not understand " + unknown.join(", ") + ". It caps " + Object.keys(UNITS).join(" and ") + ", because those are the two things an act here can spend"); return null; }
  if (!units.length) { problems.push("\"budget\" caps nothing"); return null; }
  const out = {};
  let bad = false;
  units.forEach((u) => {
    const caps = budget[u];
    if (!caps || typeof caps !== "object" || Array.isArray(caps)) { problems.push("\"budget." + u + "\" must name a period, one of " + UNITS[u].periods.join(", ")); bad = true; return; }
    const periods = Object.keys(caps);
    if (!periods.length) { problems.push("\"budget." + u + "\" names no period, so it caps nothing"); bad = true; return; }
    out[u] = {};
    periods.forEach((per) => {
      if (UNITS[u].periods.indexOf(per) < 0) {
        // ⚠ "perRound" means a TIDE round, so it is meaningless for ETH and is refused rather than
        // quietly ignored: a cap a member believes is in force and is not is worse than no cap.
        problems.push("\"budget." + u + "\" does not understand \"" + per + "\". For " + u + " the periods are: " + UNITS[u].periods.join(", "));
        bad = true; return;
      }
      if (UNITS[u].whole) {
        if (!isCount(caps[per])) { problems.push("\"budget." + u + "." + per + "\" must be a whole number of Anchor Points, and zero is a real answer: it means never"); bad = true; return; }
        out[u][per] = caps[per];
      } else {
        // ☠ A STRING, because a JSON number cannot hold wei. "0.01" is a cap; 0.01 is a rounding error
        // waiting to be argued about.
        if (typeof caps[per] !== "string" || toWei(caps[per]) === null) {
          problems.push("\"budget." + u + "." + per + "\" must be an amount of ETH written in quotes, like \"0.05\", and zero is a real answer: it means never");
          bad = true; return;
        }
        out[u][per] = caps[per];
      }
    });
  });
  return bad ? null : out;
}

/*
 * parseBrain — WHERE A MEMBER PLUGS IN THEIR OWN JUDGEMENT (4 Sep 2026, founder's design).
 * =========================================================================================
 * Everything else in this file is deterministic on purpose: same facts in, same act out, and a fact
 * that could not be read stops the agent instead of being guessed at. That is what makes every claim
 * re-derivable by a stranger. A model breaks all three of those properties — so it does not go where
 * the signing happens. It goes one rung earlier, and this block is the seam.
 *
 *   observe  ->  [ THE MEMBER'S BRAIN proposes ]  ->  these orders and this budget dispose  ->  sign
 *
 * ⚑ THE BRAIN PROPOSES, THE RULES DISPOSE. `mayPropose` names acts the member has ALREADY written
 * orders for, so a brain chooses BETWEEN things its owner permitted and can never invent a new one.
 * The budget still binds, the conditions still bind, the refusals are still printable.
 *
 * ☠☠ IT IS A COMMAND ON THEIR MACHINE, NOT A PROVIDER AND NOT AN API KEY, AND THAT IS THE WHOLE
 * DESIGN. The club names no vendor, ships no SDK, and has nothing to store: a member's own program
 * holds whatever credential it needs, exactly as `agent-key.txt` holds the signing key. This works
 * with a hosted model, a local one, or a shell script that reads a spreadsheet, and the club never
 * has to have an opinion about which. **The moment the club names a provider it has chosen a brain.**
 *
 * ☠ AND IT REFUSES A PASTED CREDENTIAL, LOUDLY. Members will try — "plug in your brain with an API
 * key" is the obvious mental model and it is the one shape this must never accept. A key in an orders
 * file is a key in a file that gets attached to a support message, so the refusal names the mistake.
 */
const BRAIN_FIELDS = ["command", "mayPropose", "timeoutSeconds"];
// Deliberately broad. A false positive costs one confused member who renames a field; a miss costs a
// leaked credential, and those are not the same size of mistake.
const LOOKS_LIKE_A_SECRET = /\b(sk|pk|api[_-]?key|bearer|token|secret|password)\b|[A-Za-z0-9_\-]{32,}/i;

function parseBrain(brain, orderedActs, problems) {
  if (brain === undefined || brain === null) return null;
  if (typeof brain !== "object" || Array.isArray(brain)) {
    problems.push("\"brain\" must say how to reach your own judgement, like { \"command\": \"node my-brain.js\", \"mayPropose\": [\"tide-commit\"] }");
    return null;
  }
  const extra = Object.keys(brain).filter((k) => BRAIN_FIELDS.indexOf(k) < 0);
  if (extra.length) {
    // ☠ Named before anything else, because this is where a pasted key would land.
    problems.push("\"brain\" does not understand " + extra.join(", ") + ". It understands " + BRAIN_FIELDS.join(", ") +
      ". ☠ If you were trying to put an API key here: it does not go in this file, and it never comes to us. Your command reads its own credential on your own machine.");
    return null;
  }
  for (const k of Object.keys(brain)) {
    const v = brain[k];
    if (typeof v === "string" && k !== "command" && LOOKS_LIKE_A_SECRET.test(v)) {
      problems.push("\"brain." + k + "\" looks like a credential. Nothing in this file is a secret: it is written to disk, it may be shared when something goes wrong, and the club never wants it. Your own command holds your own key.");
      return null;
    }
  }
  if (typeof brain.command !== "string" || !brain.command.trim()) {
    problems.push("\"brain.command\" must be a command on your machine that prints a proposal, like \"node my-brain.js\". The club does not choose a model for you and never will");
    return null;
  }
  if (LOOKS_LIKE_A_SECRET.test(brain.command) && /=|\bBearer\b|sk-/i.test(brain.command)) {
    problems.push("\"brain.command\" appears to carry a credential on its command line. Put it where your program can read it, not here: this file is written to disk and is not a secret");
    return null;
  }
  // ⚠ SAME SHAPE AS THE BUDGET RULE, AND FOR THE SAME REASON. No budget means no spending; a brain
  // that names nothing it may propose decides nothing. Silence here would be a member believing a
  // brain is in force when it is inert, which is the defect this whole file exists to prevent.
  if (!Array.isArray(brain.mayPropose) || !brain.mayPropose.length) {
    problems.push("\"brain.mayPropose\" must name the acts your brain may decide about, and there is no default. Without it your brain decides nothing at all");
    return null;
  }
  let bad = false;
  const may = [];
  brain.mayPropose.forEach((a) => {
    const act = String(a);
    if (!ACTS[act]) {
      problems.push("\"brain.mayPropose\" names \"" + act + "\", which is not an act. The acts are: " + Object.keys(ACTS).join(", "));
      bad = true; return;
    }
    // ☠☠ THE LINE THAT KEEPS THE ORDERS A CONSTITUTION. A brain chooses among acts its owner already
    // wrote down; it can never reach an act they did not permit. Take this out and the orders file
    // stops being the boundary and becomes a suggestion.
    if (orderedActs.indexOf(act) < 0) {
      problems.push("\"brain.mayPropose\" names \"" + act + "\", but you have written no orders for it. A brain chooses between things you have already allowed; it cannot add one");
      bad = true; return;
    }
    if (may.indexOf(act) < 0) may.push(act);
  });
  if (brain.timeoutSeconds !== undefined) {
    if (!isCount(brain.timeoutSeconds) || brain.timeoutSeconds < 1 || brain.timeoutSeconds > 300) {
      problems.push("\"brain.timeoutSeconds\" must be a whole number of seconds between 1 and 300. A brain that never answers must not hold the loop open for ever");
      bad = true;
    }
  }
  return bad ? null : { command: brain.command.trim(), mayPropose: may,
    timeoutSeconds: brain.timeoutSeconds === undefined ? 30 : brain.timeoutSeconds };
}

/*
 * holds(order, seen) -> { met, why }
 * ☠ FAILS CLOSED, and this is the direction that matters: a fact the club could not serve leaves the
 * condition UNMET, so an agent stops rather than acting on an assumption. The member is told which
 * fact could not be read, so a quiet agent is never a mysterious one.
 */
function holds(order, seen) {
  const when = order.when;
  if (!when) return { met: true, why: null };
  const names = Object.keys(when);
  for (let i = 0; i < names.length; i++) {
    const f = names[i];
    const value = FIELDS[f].read(seen || {});
    if (value === undefined || value === null) {
      return { met: false, why: "the club could not be read for " + f + " (" + FIELDS[f].what + "), so this condition was not met" };
    }
    const ops = Object.keys(when[f]);
    for (let j = 0; j < ops.length; j++) {
      const op = ops[j], want = when[f][op];
      if (FIELDS[f].kind === "number" && typeof value !== "number") {
        return { met: false, why: f + " did not come back as a number, so this condition was not met" };
      }
      if (!TESTS[op].holds(value, want)) {
        return { met: false, why: "you asked for " + f + " " + op + " " + want + ", and it is " + value };
      }
    }
  }
  return { met: true, why: null };
}

/*
 * plan(orders, facts, opts) -> { execute, propose, quiet }
 *   execute — an agent key may sign these now
 *   propose — valid, but only the holder may sign: hand them to the member
 *   quiet   — an order that matched nothing, with the reason, so a member is never left wondering
 * ☠ It calls the proposer and NEVER builds a request itself: the exact bytes live in one file.
 */
function plan(orders, facts, opts) {
  const o = opts || {};
  const now = o.now || Date.now();
  const del = delegatable(o.readFile);
  const seenFacts = facts.seen || {};
  const wanted = {};
  orders.list.forEach((x) => { wanted[x.act] = x; });

  // ---- the member's conditions, before anything else. An order whose `when` does not hold is not
  // an order today, and the reason is kept so the member can be told rather than left wondering.
  const held = {};
  orders.list.forEach((x) => { held[x.act] = holds(x, seenFacts); });

  // The proposer is given ONLY what the member bound. `yachtId` comes from a tide-commit order and
  // from nowhere else, so an absent order means an absent proposal rather than a guessed one.
  // ⚠ And nothing is prepared for an order whose conditions did not hold: preparing an act the
  // member's own rule rules out is how a "proposal" quietly becomes a suggestion.
  const commit = wanted["tide-commit"];
  const chain = wanted["chain-call"];
  // 🏝 The work orders, passed through exactly as the member wrote them, and only when their own
  // conditions hold. ☠ `calls` is what the RUNNER recorded this agent sending; unreadable is not empty,
  // so a delivery or a claim with no readable record prepares nothing and says why below.
  const on = (act) => wanted[act] && held[act].met ? wanted[act] : null;
  const wj = on("work-join"), wd = on("work-deliver"), wc = on("competence-claim");
  const callsKnown = !!(o.calls && o.calls.known !== false && Array.isArray(o.calls.list));
  const work = (wj || wd || wc) ? {
    join: wj ? { yacht: String(wj.yacht), discipline: wj.discipline, venue: wj.venue == null ? null : String(wj.venue), paidIn: wj.paidIn || null } : null,
    deliver: wd ? { yacht: String(wd.yacht), note: wd.note || "" } : null,
    claim: wc ? { yacht: String(wc.yacht), discipline: wc.discipline } : null
  } : null;
  const proposals = propose(facts, {
    now: o.now,
    yachtId: commit && held["tide-commit"].met ? String(commit.yacht) : null,
    // ☠ Passed straight through, never rewritten: `to` and `data` are the member's words and the club
    // has no business improving them.
    chainCall: chain && held["chain-call"].met ? { to: chain.to, value: chain.value, data: chain.data } : null,
    actingYacht: orders.actingYacht,
    work: work,
    calls: callsKnown ? o.calls.list : null,
    // 🎉 The Crew Mess: the line the RUNNER got from the member's voice (or its plain status line) before
    // planning. This file writes no words; with no line given, nothing is said.
    mess: on("mess-say") && o.mess ? o.mess : null
  });

  const ledger = ledgerFor(o.spent, now, roundField(seenFacts, "id"));
  const planned = { anchorPoints: 0n, eth: 0n };    // what this plan has already committed, per unit
  const execute = [], toPress = [], quiet = [];
  proposals.forEach((p) => {
    if (!wanted[p.act]) return;                     // the club offered it; the member did not ask
    if (!held[p.act].met) return;                   // the member's own rule says not now
    const act = ACTS[p.act];
    // ⚑ WHO SAYS AN AGENT MAY DO THIS IS A DIFFERENT QUESTION FOR THE TWO KINDS OF ACT, and getting
    // that wrong would be the club claiming authority it does not have. A club act is answered by the
    // club's own published list. A CHAIN act is answered by the CHAIN, which this file cannot read and
    // must not pretend to: the runner checks `isValidSigner` and simulates before it sends, and until
    // then the honest statement is that the member named an account and the chain will have the say.
    const route = ROUTE_OF[p.act];
    const allowed = act.onChain
      ? !!orders.actingYacht
      : (del.read && del.map[route] === true && !!orders.actingYacht);
    // ☠ WHAT IT COSTS IS READ, NEVER ASSUMED, and an unknown cost is not a free one.
    const cost = act.costs(seenFacts, wanted[p.act]);
    const money = cost ? affordable(orders, cost, ledger, planned)
                       : { ok: false, why: "the club could not be read for what this costs, and an unknown cost is not a free one" };
    const go = allowed && money.ok;
    if (go && cost.unit) planned[cost.unit] += cost.amount;
    (go ? execute : toPress).push(Object.assign({}, p, {
      spends: cost && cost.unit ? { unit: cost.unit, amount: cost.unit === "eth" ? fromWei(cost.amount) : Number(cost.amount) } : null,
      why: go
        ? (act.onChain
            ? "an order says to, and your budget covers it. The chain has the last word: your key is checked and the call is simulated before anything is sent"
            : "an order says to, a delegated key may sign this one" + (cost.unit ? ", and your budget covers it" : ", and it costs nothing"))
        : (!allowed
            ? (act.onChain ? "these orders name no actingYacht, so there is no account to act through"
               : (!del.read ? "the club's published list of what an agent may sign could not be read, so this is being handed to you"
                  : (!orders.actingYacht ? "these orders name no actingYacht, so nothing can be signed by an agent"
                     : "only the holder may sign this one")))
            : money.why)
    }));
  });

  const offered = {};
  proposals.forEach((p) => { offered[p.act] = true; });
  orders.list.forEach((x) => {
    if (offered[x.act] && held[x.act].met) return;
    // ⚠ "The club is not offering this" is true of a round already called and of a yacht that is not
    // in this wallet, and a member sent hunting through the first for a case of the second has been
    // told something useless. The ownership question is asked with the PROPOSER's own reader, so
    // there is still one definition of it ([[agent-autonomy-permissions]]).
    const notYours = x.yacht !== undefined && !ownsOrUnknown(seenFacts, x.yacht);
    const usesCalls = x.act === "work-deliver" || x.act === "competence-claim";
    // ⚑ 23 Sep 2026, the founder's first Daily watch: on a day the member had already entered the draw and kept
    // the watch by hand, both acts said "the club is not offering this", which read like a fault. The relay
    // says exactly why, in the same facts the proposer reads, so the true sentence is said instead.
    const openData = (r) => (r && r.state === "open" && r.data) || null;
    const dailyNow = openData(seenFacts.daily), standNow = openData(seenFacts.standing);
    const doneToday = (x.act === "daily-tide" && !!(dailyNow && dailyNow.tide && dailyNow.tide.entered === true))
      ? "already done today: this wallet has entered today's free draw, so there was nothing to send"
      : (x.act === "muster" && !!(standNow && standNow.entry && standNow.entry.musteredToday === true))
        ? "already done today: this wallet's watch is kept for today, so there was nothing to send"
        : null;
    quiet.push({
      act: x.act,
      why: !held[x.act].met ? held[x.act].why
        : notYours ? "yacht #" + x.yacht + " is not in this wallet, so nothing was prepared for it"
        : (usesCalls && !callsKnown) ? "the record of what your agent sent on-chain could not be read, so nothing was handed in or recorded"
        : x.act === "work-join" ? "no open work fits your rules right now, or this yacht already has a part to hand in"
        : x.act === "work-deliver" ? "no part is waiting for this yacht, or your agent has not yet sent a transaction for it"
        : x.act === "competence-claim" ? "nothing new from this yacht to record, or it still owes a part"
        : x.act === "mess-say" ? (o.messWhy || (openData(seenFacts.mess) ? "nothing to say this time" : "the Crew Mess is not open"))
        : doneToday ? doneToday
        : "nothing to do: the club is not offering this right now"
    });
  });

  // ☠ PLAIN, so a plan can be printed, saved or piped. `planned` is BigInt inside and never escapes.
  return { execute, propose: toPress, quiet, budget: orders.budget || null,
           spent: { anchorPoints: Number(planned.anchorPoints), eth: fromWei(planned.eth) } };
}

/*
 * ledgerFor — what this member's agent has already spent, as the RUNNER counted it.
 * ☠ Fails closed on purpose: with a budget written and nothing keeping count, an act that costs is
 * not executed. The count belongs on the member's machine because that is where the sending happens,
 * and a total the club kept would be a total the club could be wrong about.
 * ⚠ A new UTC day and a new round each start at nothing, which is what "in a day" and "in one round"
 * mean. Neither is a rolling window and neither pretends to be.
 */
function ledgerFor(spent, now, roundId) {
  const zero = { anchorPoints: 0n, eth: 0n };
  if (!spent || typeof spent !== "object" || spent.known === false) return { known: false, day: zero, round: zero };
  const today = new Date(now).toISOString().slice(0, 10);
  // ⚠ A count written by an older runner has no `eth` in it, and an absent count is zero spent, which
  // is the truth: nothing was sent through a version that could not send it.
  const read = (o, u) => {
    if (!o) return 0n;
    const v = o[u];
    if (v === undefined || v === null) return 0n;
    if (u === "eth") { const w = toWei(v); return w === null ? 0n : w; }
    return isCount(v) ? BigInt(v) : 0n;
  };
  const sameDay = spent.day === today;
  const sameRound = spent.round && roundId != null && String(spent.round.id) === String(roundId);
  return {
    known: true,
    day: { anchorPoints: sameDay ? read(spent, "anchorPoints") : 0n, eth: sameDay ? read(spent, "eth") : 0n },
    round: { anchorPoints: sameRound ? read(spent.round, "anchorPoints") : 0n, eth: sameRound ? read(spent.round, "eth") : 0n }
  };
}

/*
 * affordable — the member's own ceiling, and the only ceiling that exists.
 * ☠☠ NO BUDGET MEANS NO SPENDING. The club does not write a cap on a member's behalf, so an act that
 * costs and has no budget behind it is handed back rather than run. ⚠ Handed back, never dropped: a
 * budget binds the AGENT, and the member's own hand was never the thing being limited.
 */
function affordable(orders, cost, ledger, planned) {
  if (!cost.unit || cost.amount <= 0n) return { ok: true, why: null };
  const unit = cost.unit;
  const b = orders.budget;
  if (!b || !b[unit]) return { ok: false, why: "these orders write no budget in " + unit + ", so your agent will not spend " +
    UNITS[unit].what + ". You can still press this yourself" };
  if (!ledger.known) return { ok: false, why: "nothing is keeping count of what your agent has spent, so your budget could not be checked" };
  const caps = b[unit];
  const gone = (per) => (per === "perDay" ? ledger.day[unit] : ledger.round[unit]) + ((planned && planned[unit]) || 0n);
  const over = Object.keys(caps).find((per) => gone(per) + cost.amount > asWei(unit, caps[per]));
  if (over) {
    return { ok: false, why: "you set " + amount(unit, caps[over]) + " " + PERIODS[over] + ", " + amount(unit, gone(over)) +
      " of that has gone, and this costs " + amount(unit, cost.amount) + ". Your agent stops here, and you can still press it yourself" };
  }
  return { ok: true, why: null };
}


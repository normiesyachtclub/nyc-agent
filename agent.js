const ACCOUNT_ABI = [
  "function execute(address to, uint256 value, bytes data, uint8 operation) payable returns (bytes)",
  "function isValidSigner(address signer, bytes context) view returns (bytes4)"
];
const SIGNER_OK = "0x523e3260";

/*
 * chainCall — the one act that leaves the club.
 * ☠☠ TWO REFUSALS BEFORE ANYTHING IS BROADCAST, and both are the club being useful rather than
 * protective: it cannot make an arbitrary call safe, but it can refuse to let somebody pay gas for a
 * transaction that was never going to work.
 *   1. THE CHAIN IS ASKED WHETHER THIS KEY MAY ACT. `isValidSigner` on the account itself, read live.
 *      A revoked or never granted key stops here instead of reverting after the fee is paid.
 *   2. THE CALL IS SIMULATED. `eth_call` runs it against current state; if it reverts, nothing is sent.
 * ⚠ Neither check makes the CALLDATA safe, and nothing can: what the member wrote is what runs.
 */
async function chainCall(act, wallet) {
  const provider = await reader();
  if (!provider) return { ok: false, why: "no Ethereum reader answered, so nothing was sent" };
  const signer = wallet.connect(provider);
  const account = accountOf(act.chain.actingYacht);
  const c = new ethers.Contract(account, ACCOUNT_ABI, provider);

  let may;
  try { may = await c.isValidSigner(await signer.getAddress(), "0x"); }
  catch (e) { return { ok: false, why: "could not ask account " + account + " whether this may act: " + e.message }; }
  if (may !== SIGNER_OK) {
    return { ok: false, why: "account " + account + " does not accept this signer. Grant it on The Purser, or check the yacht is still yours" };
  }

  const value = ethers.parseEther(String(act.chain.value || "0"));
  const data = c.interface.encodeFunctionData("execute", [act.chain.to, value, act.chain.data || "0x", 0]);
  try { await provider.call({ to: account, from: await signer.getAddress(), data: data }); }
  catch (e) {
    return { ok: false, why: "the call was simulated and it failed, so nothing was sent: " + String(e.shortMessage || e.message).slice(0, 120) };
  }

  const tx = await signer.sendTransaction({ to: account, data: data });
  const receipt = await tx.wait();
  return { ok: true, hash: tx.hash, status: receipt && receipt.status };
}

/* ---- where the key comes from -------------------------------------------------------------------
 * ⚑ A FILE BESIDE THE ORDERS, OR THE ENVIRONMENT. The environment variable came first and it still
 * wins, because anybody keeping keys in a secret manager is already doing better than this. But it
 * was the ONLY way in, and setting an environment variable on Windows is where a member's evening
 * ends: it is the last piece of terminal knowledge in a flow that otherwise needs none.
 * So: `agent-key.txt` next to the orders file, which is the folder they already have open because
 * that is where the two downloads went.
 *
 * ☠ THE FILE MAY CARRY COMMENTS, AND THAT IS NOT A CONVENIENCE. A bare key in a bare file is a file
 * nobody can identify three months later, and an unidentified secret is one that gets shared. The
 * page that writes it puts a warning at the top, so this has to read past it: every line starting
 * with `#` is skipped, and the first thing that looks like a key is the key.
 * ⚠ It is still never printed, never logged, and never written by this file.
 */
// ⚑ 24 Sep 2026, the founder's own first run on GitHub: the secret held something that was not a key, the run
// printed "invalid private key" among other lines, signed nothing, and still went GREEN. Two fixes. The secret is
// read as forgivingly as the file is (quotes, spaces, the whole file pasted, a key without 0x), and a secret that
// still holds no key says WHAT it holds instead, in one sentence, and turns the run red (`keyTrouble`, `once`).
// ☠ Neither ever prints the value: only its shape.
function keyFromText(raw) {
  const line = String(raw || "").split(/\r?\n/).map((l) => l.trim().replace(/^["']+|["']+$/g, "").trim())
    .find((l) => l && l[0] !== "#" && /^(0x)?[0-9a-fA-F]{64}$/.test(l));
  return line ? (line[0] === "0" && line[1] === "x" ? line : "0x" + line) : "";
}
function keyTrouble() {
  const raw = process.env.NYC_AGENT_KEY;
  if (!raw || keyFromText(raw)) return null;
  const t = String(raw).trim().replace(/^["']+|["']+$/g, "").trim();
  if (/^(#\s*)?(0x)?[0-9a-fA-F]{40}$/.test(t)) {
    return "NYC_AGENT_KEY holds an ADDRESS (0x and 40 characters): that is the half you give out. The secret needs " +
      "the KEY itself: the LAST line of agent-key.txt, 0x and 64 more characters, alone, with nothing around it.";
  }
  return "NYC_AGENT_KEY is set, but it is not a key: it has " + t.length + " characters, and a key has 66 (0x and 64 " +
    "more). Put the LAST line of agent-key.txt in it, alone, with no spaces or quotes around it.";
}

function agentKey(ordersFile) {
  if (process.env.NYC_AGENT_KEY) return keyFromText(process.env.NYC_AGENT_KEY);
  const dir = ordersFile ? path.dirname(path.resolve(ordersFile)) : process.cwd();
  for (const name of ["agent-key.txt", "agent-key"]) {
    try {
      const raw = fs.readFileSync(path.join(dir, name), "utf8");
      const line = raw.split(/\r?\n/).map((l) => l.trim())
        .find((l) => l && l[0] !== "#" && /^(0x)?[0-9a-fA-F]{64}$/.test(l));
      if (line) return line[0] === "0" && line[1] === "x" ? line : "0x" + line;
    } catch (e) { /* the next name, then the environment's answer, which is none */ }
  }
  return "";
}


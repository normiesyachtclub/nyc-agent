function news(facts, opts) {
  const o = opts || {};
  const handled = (o.handled || []).map(String);
  const s = (facts && facts.seen) || {};
  const out = [];
  const add = (key, line) => out.push({ key: key, line: line });
  const today = String((facts && facts.at) || new Date().toISOString()).slice(0, 10);
  const me = String((facts && facts.wallet) || "").toLowerCase();

  // 1. what the member's own agent tried and was refused. First, because it is the one thing here
  //    nobody else will ever tell them.
  (o.failed || []).forEach((f) => {
    add("failed:" + f.act + ":" + today,
      "Your agent tried to " + (ACT_SAID[f.act] || f.act) + " and it did not go through: " +
      String(f.why || "no reason was given").replace(/\s+/g, " ").slice(0, 160));
  });

  // 🏝 1b. THE MEMBER'S OWN ISLANDS, straight after anything refused (founder, 19 Sep 2026: islands must have
  //     a fundamental role). The key carries the island's state, so waking it or naming it is news again.
  //     ☠ A partial list says nothing: an island missing from it is not an island that is gone.
  const isl = D(s.islands);
  const all = isl && isl.partial !== true && Array.isArray(isl.islands) ? isl.islands : null;
  const act = D(s.activation);
  const nameOf = (x) => (x.name ? x.name + " (#" + x.islandId + ")" : "island #" + x.islandId);
  const aOr = (w) => (/^[AEIOU]/i.test(String(w)) ? "an " : "a ") + w;
  const stateOf = (x) => (x.awake ? "awake" : "asleep") + ":" + (x.name || "");
  const mineIsl = all && me ? all.filter((x) => String(x.owner || "").toLowerCase() === me) : [];
  mineIsl.forEach((x) => {
    let line = "Your island " + nameOf(x) + ", " + (x.grade ? aOr(x.grade) + ", " : "") + "builds up " +
      x.anchorPointsPerDay + " anchor points a day for you.";
    if (!x.awake) {
      const price = act && typeof act.apPerPointOfGrade === "number" && typeof x.score === "number" ? x.score * act.apPerPointOfGrade : null;
      line += " It is asleep" + (price ? ": waking it costs " + price + " anchor points, once, and an island must be awake to be named and to open a service" : "") + ".";
    }
    add("my-island:" + x.islandId + ":" + stateOf(x), line);
  });

  // 2. the season. Told once when it is on, and once when the next one has a date.
  const reg = D(s.regatta);
  const g = reg && reg.season;
  if (g && g.status === "active") {
    add("season:" + g.id, (g.name || "The season") + " is on: day " + g.day + " of " + g.days +
      (g.endAt ? ", and it closes " + when(g.endAt) : "") + ". Every day you keep your watch counts, and a missed day cannot be made up.");
  } else if (g && g.nextSeasonAt) {
    add("next-season:" + g.nextSeasonAt, "The next season" + (g.nextSeasonName ? ", " + g.nextSeasonName + "," : "") +
      " opens " + when(g.nextSeasonAt) + ".");
  }

  // 3. today's two free acts, unless the member's agent just did them.
  const daily = D(s.daily);
  if (daily && daily.tide && daily.tide.entered === false && handled.indexOf("daily-tide") < 0) {
    add("draw:" + daily.tide.day, "Today's free draw is open and you are not in it. It costs nothing" +
      (daily.tide.closesAt ? ", and it closes " + when(daily.tide.closesAt) : "") + ".");
  }
  const st = D(s.standing);
  if (g && g.status === "active" && st && st.entry && st.entry.musteredToday === false && handled.indexOf("muster") < 0) {
    add("watch:" + g.id + ":" + today, "You have not kept today's watch in " + (g.name || "the Regatta") +
      ". It closes at midnight UTC.");
  }

  // 4. the Sunday round: once when it opens, once when anybody may call it.
  const tide = D(s.tide);
  const r = tide && tide.round;
  if (r && !r.closed) {
    const PRIZE_SAID = { yacht: "a yacht from the club's vault", store: "an item from the club's shop", berth: "a berth",
      "forging-slot": "a forging slot", "tide-mark": "a Tide mark", naming: "a naming right" };
    add("tide:" + r.id, "Tide round " + r.id + " is open. It draws for " + (PRIZE_SAID[r.prize] || r.prize || "a prize the club did not state") +
      (r.closesAt ? ", and it closes " + when(r.closesAt) : "") + ".");
    if (r.callable) add("tide-callable:" + r.id, "Tide round " + r.id + " can be called now, by any member.");
  }

  // 5. a prize with this wallet's name on it.
  const yp = D(s.yachtPrize);
  if (me && yp && Array.isArray(yp.awarded)) {
    yp.awarded.filter((a) => String(a.wallet || "").toLowerCase() === me).forEach((a) => {
      add("prize:" + a.tokenId + ":" + (a.delivered ? "delivered" : "owed"),
        (a.name || "A yacht") + " was awarded to you" + (a.why ? " (" + a.why + ")" : "") +
        (a.delivered ? " and it has been delivered to this wallet." : ". It has not been delivered yet."));
    });
  }

  // 6. a berth this wallet may take.
  const b = D(s.berths);
  if (b && !b.mine && b.eligible === true) add("berth-open", "A berth is open for you to take.");

  // 7. work posted on the board. Named, never ranked: the oldest first, because that is the only
  //    order the club has, and a line per job up to five so a busy board is not a wall of text.
  //    🏝 Work at the member's OWN island comes before the rest, because that island is theirs, not because
  //    the work is better: within each group the order is still the oldest first.
  const opps = D(s.opportunities);
  const myIds = mineIsl.map((x) => String(x.islandId));
  const islName = (v) => { const x = all && all.find((i) => String(i.islandId) === String(v)); return x ? nameOf(x) : "island " + v; };
  const board = opps && Array.isArray(opps.opportunities)
    ? opps.opportunities.filter((x) => x && x.status === "open")
      .sort((x, y) => ((myIds.indexOf(String(y.venue)) >= 0) - (myIds.indexOf(String(x.venue)) >= 0)) || ((x.postedAt || 0) - (y.postedAt || 0)))
    : [];
  board.slice(0, 5).forEach((x) => {
    const atMine = myIds.indexOf(String(x.venue)) >= 0;
    add("work:" + x.id, (atMine ? "Work posted at YOUR island " + islName(x.venue) + ": " : "Work posted: ") +
      (x.discipline || "a part") + (atMine ? "" : " at " + (String(x.venue) === "marina" ? "the marina" : islName(x.venue))) + ", " +
      (Array.isArray(x.parts) ? x.parts.length : "?") + " part" + (Array.isArray(x.parts) && x.parts.length === 1 ? "" : "s") +
      (x.symbol ? ", paid in " + x.symbol : "") + (x.deadline ? ", until " + when(x.deadline) : "") + ".");
  });
  if (board.length > 5) add("work-more:" + board.length, "And " + (board.length - 5) + " more pieces of posted work on the board.");

  // 🏝 8. the islands on the map, for everybody: the places the club's agents work. One line per island, new
  //    when it is forged and again when it wakes or is named. The member's own were said above. At most five
  //    a run, newest first, so the first run for a new member is not a wall.
  if (all) {
    const others = all.filter((x) => myIds.indexOf(String(x.islandId)) < 0).slice().reverse();
    others.slice(0, 5).forEach((x) => {
      add("island:" + x.islandId + ":" + stateOf(x), "On the map: " + nameOf(x) + ", " + (x.grade ? aOr(x.grade) : "an island") +
        (x.awake ? (x.name ? "" : ", awake and not named yet") : ", still asleep") +
        (x.services ? ", with room for " + x.services + " service" + (x.services === 1 ? "" : "s") : "") + ".");
    });
    if (others.length > 5) add("islands-more:" + all.length, all.length + " islands are on the map in all.");
  }

  return out;
}

